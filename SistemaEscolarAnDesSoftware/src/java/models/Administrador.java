package models;

/**
 *
 * @author issler
 */
public class Administrador {
    int id;
    Pessoa pessoa;

    public Administrador(int id, Pessoa pessoa) {
        this.id = id;
        this.pessoa = pessoa;
    }

    public Administrador() {
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public Pessoa getPessoa() {
        return pessoa;
    }

    public void setPessoa(Pessoa pessoa) {
        this.pessoa = pessoa;
    }
    
}
