package models;

import java.time.LocalDate;

/**
 *
 * @author issler
 */
public class Solicitacao {
    int id;
    String titulo;
    LocalDate data;
    String status;
    String descricao;
    Aluno aluno;

    public Solicitacao(int id, String titulo, LocalDate data, String status, String descricao, Aluno aluno) {
        this.id = id;
        this.titulo = titulo;
        this.data = data;
        this.status = status;
        this.descricao = descricao;
        this.aluno = aluno;
    }

    public Solicitacao() {
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getTitulo() {
        return titulo;
    }

    public void setTitulo(String titulo) {
        this.titulo = titulo;
    }

    public LocalDate getData() {
        return data;
    }

    public void setData(LocalDate data) {
        this.data = data;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public String getDescricao() {
        return descricao;
    }

    public void setDescricao(String descricao) {
        this.descricao = descricao;
    }

    public Aluno getAluno() {
        return aluno;
    }

    public void setAluno(Aluno aluno) {
        this.aluno = aluno;
    }
    
}
