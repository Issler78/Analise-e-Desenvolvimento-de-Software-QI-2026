package models;

/**
 *
 * @author issler
 */
public class Turno {
    int id;
    String turno;

    public Turno(int id, String turno) {
        this.id = id;
        this.turno = turno;
    }

    public Turno() {
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getTurno() {
        return turno;
    }

    public void setTurno(String turno) {
        this.turno = turno;
    }
    
}
