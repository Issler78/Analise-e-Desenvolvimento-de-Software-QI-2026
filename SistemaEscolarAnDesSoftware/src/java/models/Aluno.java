package models;

/**
 *
 * @author issler
 */
public class Aluno {
    int id;
    String situacao;
    Pessoa pessoa;
    Turma turma;

    public Aluno(int id, String situacao, Pessoa pessoa, Turma turma) {
        this.id = id;
        this.situacao = situacao;
        this.pessoa = pessoa;
        this.turma = turma;
    }

    public Aluno() {
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getSituacao() {
        return situacao;
    }

    public void setSituacao(String situacao) {
        this.situacao = situacao;
    }

    public Pessoa getPessoa() {
        return pessoa;
    }

    public void setPessoa(Pessoa pessoa) {
        this.pessoa = pessoa;
    }

    public Turma getTurma() {
        return turma;
    }

    public void setTurma(Turma turma) {
        this.turma = turma;
    }
    
}
